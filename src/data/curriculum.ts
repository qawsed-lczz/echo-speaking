export const allSentences: Sentence[] = modules.flatMap((m) => m.sentences);

export const sentenceById: Record<string, Sentence> = Object.fromEntries(
  allSentences.map((s) => [s.id, s])
);

export const moduleById: Record<string, Module> = Object.fromEntries(
  modules.map((m) => [m.id, m])
);

export const moduleOfSentence = (id: string): Module => {
  const sentence = sentenceById[id];
  return moduleById[sentence.moduleId];
};

/** Strip markup for speech synthesis and accessibility labels. */
export const plainText = (text: string): string => text.replace(/[{}*]/g, '');

export const estimateMinutes = (sentenceCount: number): number =>
  Math.max(2, Math.round(sentenceCount * 1.6));
